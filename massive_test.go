func TestMassiveQuestions(t *testing.T) {
	// Загружаем конфигурацию
	cfg := loadConfig()
	
	// Проверяем доступность Ollama
	ctx, cancel := context.WithTimeout(context.Background(), 5*time.Second)
	defer cancel()
	
	_, err := pickOllamaModel(ctx, cfg)
	if err != nil {
		t.Skipf("Ollama недоступна: %v", err)
	}
	
	// Статистика
	total := len(massiveTestQuestions)
	success := 0
	failed := 0
	noAnswer := 0
	
	// Файл для записи результатов
	outFile, err := os.Create("massive_test_results.txt")
	if err != nil {
		t.Fatalf("Не удалось создать файл результатов: %v", err)
	}
	defer outFile.Close()
	
	fmt.Fprintf(outFile, "=== МАССОВОЕ ТЕСТИРОВАНИЕ ВОПРОСОВ ===\n")
	fmt.Fprintf(outFile, "Дата: %s\n", time.Now().Format("2006-01-02 15:04:05"))
	fmt.Fprintf(outFile, "Всего вопросов: %d\n\n", total)
	
	// Проходим по всем вопросам
	for i, tc := range massiveTestQuestions {
		fmt.Printf("\n[%d/%d] Категория: %s\n", i+1, total, tc.category)
		fmt.Printf("Вопрос: %s\n", tc.question)
		fmt.Fprintf(outFile, "\n========================================\n")
		fmt.Fprintf(outFile, "[%d/%d] Категория: %s\n", i+1, total, tc.category)
		fmt.Fprintf(outFile, "Вопрос: %s\n", tc.question)
		
		// Создаем контекст для запроса
		ctx, cancel := context.WithTimeout(context.Background(), 60*time.Second)
		
		// Генерируем ответ
		answer, sources, err := GenerateAnswer(ctx, cfg, tc.question, nil)
		cancel()
		
		if err != nil {
			fmt.Printf("ОШИБКА: %v\n", err)
			fmt.Fprintf(outFile, "ОШИБКА: %v\n", err)
			failed++
			continue
		}
		
		// Проверяем, найден ли ответ
		if answer == "" || strings.Contains(answer, "не нашёл информации по этому вопросу") {
			fmt.Printf("❌ НЕТ ОТВЕТА\n")
			fmt.Fprintf(outFile, "Результат: ❌ НЕТ ОТВЕТА\n")
			noAnswer++
		} else {
			// Проверяем наличие ожидаемых ключевых слов
			answerNorm := normalize(answer)
			expectedNorm := normalize(tc.expected)
			
			if strings.Contains(answerNorm, expectedNorm) {
				fmt.Printf("✅ УСПЕХ\n")
				fmt.Fprintf(outFile, "Результат: ✅ УСПЕХ\n")
				success++
			} else {
				fmt.Printf("⚠️ ОТВЕТ БЕЗ ОЖИДАЕМЫХ КЛЮЧЕВЫХ СЛОВ\n")
				fmt.Fprintf(outFile, "Результат: ⚠️ ОТВЕТ БЕЗ ОЖИДАЕМЫХ КЛЮЧЕВЫХ СЛОВ (ожидалось: %s)\n", tc.expected)
				success++ // Всё равно засчитываем, так как ответ есть
			}
		}
		
		fmt.Printf("Ответ: %s\n", answer)
		fmt.Printf("Источники: %d\n", len(sources))
		
		fmt.Fprintf(outFile, "Ответ: %s\n", answer)
		fmt.Fprintf(outFile, "Источники: %d\n", len(sources))
		for j, src := range sources {
			fmt.Fprintf(outFile, "  [%d] %s\n", j+1, src.Name)
		}
		
		// Небольшая пауза между запросами
		time.Sleep(500 * time.Millisecond)
	}
	
	// Итоговая статистика
	fmt.Printf("\n\n=== ИТОГОВАЯ СТАТИСТИКА ===\n")
	fmt.Printf("Всего вопросов: %d\n", total)
	fmt.Printf("✅ Успешно (найден ответ): %d (%.1f%%)\n", success, float64(success)/float64(total)*100)
	fmt.Printf("❌ Не найден ответ: %d (%.1f%%)\n", noAnswer, float64(noAnswer)/float64(total)*100)
	fmt.Printf("🔥 Ошибки: %d (%.1f%%)\n", failed, float64(failed)/float64(total)*100)
	
	fmt.Fprintf(outFile, "\n\n=== ИТОГОВАЯ СТАТИСТИКА ===\n")
	fmt.Fprintf(outFile, "Всего вопросов: %d\n", total)
	fmt.Fprintf(outFile, "✅ Успешно (найден ответ): %d (%.1f%%)\n", success, float64(success)/float64(total)*100)
	fmt.Fprintf(outFile, "❌ Не найден ответ: %d (%.1f%%)\n", noAnswer, float64(noAnswer)/float64(total)*100)
	fmt.Fprintf(outFile, "🔥 Ошибки: %d (%.1f%%)\n", failed, float64(failed)/float64(total)*100)
	
	// Если слишком много неуспешных ответов, тест провален
	successRate := float64(success) / float64(total) * 100
	if successRate < 80.0 {
		t.Errorf("Недостаточный процент успеха: %.1f%% (требуется минимум 80%%)", successRate)
	}
	
	log.Printf("Результаты сохранены в massive_test_results.txt")
}

